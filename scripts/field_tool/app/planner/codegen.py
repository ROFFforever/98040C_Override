"""Plan -> C++ (.h + .cpp). Two styles:
  lines:    void name(drivetrain* chassis){ await(...); chassis->rotate(0)->schedule(); pros::delay(100); ... }
            Groups become await(new Sequence({...})) / (new Sequence({...}))->schedule().
  sequence: Sequence* name(drivetrain* chassis){ return new Sequence({...}); }  (like Autons/SoloAWP.cpp)
The .cpp is the source of truth: its first line carries the settings that aren't visible in the code (time limit,
start pose when there's no setPose) and parse.py reads the whole file back, so hand edits are picked up by the tool.
(Files from the older version carry a hash of the rest instead, see is_legacy / hand_edited.)"""
import hashlib

from app import field_config as cfg
from app.planner.plan import Group, identifier
from app.planner.steps import num

IND = "    "
TAG = "hash:"                   #legacy first-line hash
LEGACY_TAG = "Generated by the field tool"
PLAN_TAG = "field_tool plan"    #first line of a plan's .cpp


def _arg(prm, value):
    if prm.kind == "bool":
        return "true" if value else "false"
    if prm.kind == "choice":
        return f"{prm.cpp_enum}::{value}"
    if prm.kind == "auto":
        return prm.cpp_auto if value is None else num(value)
    if prm.kind == "int":
        return str(int(value))
    return num(value)


def command_expr(step):
    """C++ expression for a command-type step, leaving off trailing arguments that are at their default."""
    kind = step.kind
    args = [(prm, step.params[prm.name]) for prm in kind.params]
    last = max([i for i, (prm, v) in enumerate(args) if not prm.optional or v != prm.default], default=-1)
    return f"{kind.call}({', '.join(_arg(prm, v) for prm, v in args[:last + 1])})"


def _comment(note):
    return f" // {note.strip()}" if note.strip() else ""


def _code_lines(step):
    return [ln.rstrip() for ln in step.params["text"].strip().splitlines() if ln.strip()]


def _ensure_semicolon(line):
    """Adds a ';' after the code part of a line unless it already ends a statement (or is only a comment)."""
    code, sep, comment = line.partition("//")
    stripped = code.rstrip()
    if not stripped or stripped.endswith((";", "}", "{")) or stripped.startswith("#"):
        return line
    return stripped + ";" + ((" " + sep + comment) if sep else "")


def _element(step):
    """A step as one element of a Sequence's command list (no trailing comma)."""
    if step.type == "wait":
        return f"new WaitCommand({int(step.params['ms'])})"
    if step.type == "code":  #has to be a Command* expression in here
        return " ".join(ln.strip() for ln in _code_lines(step)).rstrip(";") or "nullptr /* empty code step */"
    return command_expr(step)


def _sequence_block(steps, indent):
    """'new Sequence({' ... '})' split over lines, elements indented one level deeper."""
    out = ["new Sequence({"]
    for k, s in enumerate(steps):
        comma = "," if k < len(steps) - 1 else ""
        out.append(f"{indent}{IND}{_element(s)}{comma}{_comment(s.note)}")
    out.append(f"{indent}}})")
    return out


def _lines_body(plan):
    body = []
    for item in plan.items:
        if isinstance(item, Group):
            block = _sequence_block(item.steps, IND)
            if item.is_async:
                block[0] = "(" + block[0]
                block[-1] += ")->schedule();"
            else:
                block[0] = "await(" + block[0]
                block[-1] += ");"
            block[0] += _comment(item.note)
            body.append(IND + block[0])
            body += block[1:]
            continue
        if item.type == "wait":
            body.append(f"{IND}pros::delay({int(item.params['ms'])});{_comment(item.note)}")
        elif item.type == "code":
            code = _code_lines(item)
            if code:
                code[-1] = _ensure_semicolon(code[-1])
            if item.note.strip():
                body.append(f"{IND}// {item.note.strip()}")
            body += [IND + ln for ln in code]
        elif item.is_async:
            body.append(f"{IND}{command_expr(item)}->schedule();{_comment(item.note)}")
        else:
            body.append(f"{IND}await({command_expr(item)});{_comment(item.note)}")
    return body


def _wall_pose(plan):
    return plan.set_pose and plan.wall_pose


def _signature(plan, fn):
    wall = "WallLocalization* wallLoc" if _wall_pose(plan) else ""
    params = ", ".join(p for p in ("drivetrain* chassis", wall, plan.extra_params.strip()) if p)
    ret = "void" if plan.style == "lines" else "Sequence*"
    return f"{ret} {fn}({params})"


def _set_pose(plan):
    pose = f"chassis->setPose({num(plan.start_x)}, {num(plan.start_y)}, degToRad({num(plan.start_heading)}));"
    if not _wall_pose(plan):
        return f"{IND}{pose} //starting pose"
    quad = ("Pos" if plan.start_x >= 0 else "Neg") + "X" + ("Pos" if plan.start_y >= 0 else "Neg") + "Y"
    return "\n".join([
        f"{IND}if(!wallLoc->set_initial_pose({num(plan.start_heading)}, WallLocalization::Quadrant::{quad})){{"
        " //seed pose from the wall sensors",
        f"{IND}{IND}{pose} //sensors missed, use the nominal start pose",
        f"{IND}}}"])


def _used_includes(plan):
    steps = [s for _, s in plan.flat()]
    inc = []
    if plan.style == "lines":
        inc.append("CommandScheduler/commandScheduler.h")  #await()
    for s in steps:
        inc += s.kind.includes
    in_sequence = plan.style == "sequence" or any(isinstance(it, Group) for it in plan.items)
    if in_sequence and any(s.type == "wait" for s in steps):
        inc.append("Commands/WaitCommand.h")
    if plan.set_pose:
        inc.append("util/mathUtils.h")  #degToRad
    if _wall_pose(plan):
        inc.append("Commands/Localization/WallLocalization.h")
    return list(dict.fromkeys(inc))  #dedupe, keep order


def _meta_line(plan):
    meta = f"time_limit={num(plan.time_limit)}"
    if not plan.set_pose:  #otherwise the start pose is in the setPose line
        meta += f" start={num(plan.start_x)},{num(plan.start_y)},{num(plan.start_heading)}"
    return f"// {PLAN_TAG}: edit this file freely, the field tool reads it back. {meta}"


def generate(plan):
    """-> (header text, cpp text) for the plan."""
    fn = identifier(plan.name)
    extra = [h.strip() for h in plan.extra_includes.split(",") if h.strip()]
    wall_inc = ['#include "Commands/Localization/WallLocalization.h"'] if _wall_pose(plan) else []
    header = "\n".join(["#pragma once", '#include "Subsystems/drivetrain.h"'] + wall_inc
                       + [f'#include "{h}"' for h in extra]
                       + ["", f"{_signature(plan, fn)};", ""])

    body = [f'#include "GeneratedAutons/{fn}.h"'] + [f'#include "{h}"' for h in _used_includes(plan)]
    body += ["", _signature(plan, fn) + "{"]
    if plan.set_pose:
        body.append(_set_pose(plan))
    if plan.style == "lines":
        body += _lines_body(plan)
    else:
        steps = [s for _, s in plan.flat()]
        block = _sequence_block(steps, IND)
        body.append(IND + "return " + block[0])
        body += block[1:-1] + [block[-1] + ";"]
    body += ["}", ""]
    return header, _meta_line(plan) + "\n" + "\n".join(body)


def export_paths(plan):
    fn = identifier(plan.name)
    return cfg.EXPORT_INC_DIR / f"{fn}.h", cfg.EXPORT_SRC_DIR / f"{fn}.cpp"


def first_line(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return f.readline()
    except OSError:
        return ""


def is_plan_file(path):
    """True for a .cpp this tool wrote (current or legacy header), so it's safe to read/overwrite."""
    line = first_line(path)
    return PLAN_TAG in line or LEGACY_TAG in line


def is_legacy(path):
    return LEGACY_TAG in first_line(path) and TAG in first_line(path)


def hand_edited(path):
    """Legacy files only: True if the file isn't exactly what the old tool last wrote."""
    if not path.exists():
        return False
    text = path.read_text()
    first, _, rest = text.partition("\n")
    if TAG not in first:
        return True
    return first.rsplit(TAG, 1)[1].strip() != hashlib.sha1(rest.encode()).hexdigest()[:12]
