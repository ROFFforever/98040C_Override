"""Plan -> C++ (.h + .cpp). Two styles:
  lines:    void name(drivetrain* chassis){ await(...); chassis->rotate(0)->schedule(); pros::delay(100); ... }
            Groups become await(new Sequence({...})) / (new Sequence({...}))->schedule().
  sequence: Sequence* name(drivetrain* chassis){ return new Sequence({...}); }  (like Autons/SoloAWP.cpp)
The first line of each file carries a hash of the rest, so export can tell when a file was edited by hand."""
import hashlib

from app import field_config as cfg
from app.planner.plan import Group, identifier
from app.planner.steps import num

IND = "    "
TAG = "hash:"


def _arg(prm, value):
    if prm.kind == "bool":
        return "true" if value else "false"
    if prm.kind == "choice":
        return f"{prm.cpp_enum}::{value}"
    if prm.kind == "auto":
        return prm.cpp_auto if value is None else num(value)
    if prm.kind == "int":
        return str(int(value))
    return num(value)


def command_expr(step):
    """C++ expression for a command-type step, leaving off trailing arguments that are at their default."""
    kind = step.kind
    args = [(prm, step.params[prm.name]) for prm in kind.params]
    last = max([i for i, (prm, v) in enumerate(args) if not prm.optional or v != prm.default], default=-1)
    return f"{kind.call}({', '.join(_arg(prm, v) for prm, v in args[:last + 1])})"


def _comment(note):
    return f" // {note.strip()}" if note.strip() else ""


def _code_lines(step):
    return [ln.rstrip() for ln in step.params["text"].strip().splitlines() if ln.strip()]


def _element(step):
    """A step as one element of a Sequence's command list (no trailing comma)."""
    if step.type == "wait":
        return f"new WaitCommand({int(step.params['ms'])})"
    if step.type == "code":  #has to be a Command* expression in here
        return " ".join(ln.strip() for ln in _code_lines(step)).rstrip(";") or "nullptr /* empty code step */"
    return command_expr(step)


def _sequence_block(steps, indent):
    """'new Sequence({' ... '})' split over lines, elements indented one level deeper."""
    out = ["new Sequence({"]
    for k, s in enumerate(steps):
        comma = "," if k < len(steps) - 1 else ""
        out.append(f"{indent}{IND}{_element(s)}{comma}{_comment(s.note)}")
    out.append(f"{indent}}})")
    return out


def _lines_body(plan):
    body = []
    for item in plan.items:
        if isinstance(item, Group):
            block = _sequence_block(item.steps, IND)
            if item.is_async:
                block[0] = "(" + block[0]
                block[-1] += ")->schedule();"
            else:
                block[0] = "await(" + block[0]
                block[-1] += ");"
            block[0] += _comment(item.note)
            body.append(IND + block[0])
            body += block[1:]
            continue
        if item.type == "wait":
            body.append(f"{IND}pros::delay({int(item.params['ms'])});{_comment(item.note)}")
        elif item.type == "code":
            code = _code_lines(item)
            if code and not code[-1].rstrip().endswith((";", "}")):
                code[-1] += ";"
            if item.note.strip():
                body.append(f"{IND}// {item.note.strip()}")
            body += [IND + ln for ln in code]
        elif item.is_async:
            body.append(f"{IND}{command_expr(item)}->schedule();{_comment(item.note)}")
        else:
            body.append(f"{IND}await({command_expr(item)});{_comment(item.note)}")
    return body


def _signature(plan, fn):
    params = ", ".join(p for p in ("drivetrain* chassis", plan.extra_params.strip()) if p)
    ret = "void" if plan.style == "lines" else "Sequence*"
    return f"{ret} {fn}({params})"


def _set_pose(plan):
    return (f"{IND}chassis->setPose({num(plan.start_x)}, {num(plan.start_y)}, degToRad({num(plan.start_heading)}));"
            " //starting pose")


def _used_includes(plan):
    steps = [s for _, s in plan.flat()]
    inc = []
    if plan.style == "lines":
        inc.append("CommandScheduler/commandScheduler.h")  #await()
    for s in steps:
        inc += s.kind.includes
    in_sequence = plan.style == "sequence" or any(isinstance(it, Group) for it in plan.items)
    if in_sequence and any(s.type == "wait" for s in steps):
        inc.append("Commands/WaitCommand.h")
    if plan.set_pose:
        inc.append("util/mathUtils.h")  #degToRad
    return list(dict.fromkeys(inc))  #dedupe, keep order


def _stamp(body, source):
    """First line: what generated it + a hash of everything after it."""
    digest = hashlib.sha1(body.encode()).hexdigest()[:12]
    return f"// Generated by the field tool from {source} - edit the plan and re-export. {TAG}{digest}\n" + body


def source_name(plan):
    return f"scripts/field_tool/autons/{identifier(plan.name)}.json"


def generate(plan):
    """-> (header text, cpp text) for the plan."""
    fn = identifier(plan.name)
    extra = [h.strip() for h in plan.extra_includes.split(",") if h.strip()]
    header = "\n".join(["#pragma once", '#include "Subsystems/drivetrain.h"']
                       + [f'#include "{h}"' for h in extra]
                       + ["", f"{_signature(plan, fn)};", ""])

    body = [f'#include "GeneratedAutons/{fn}.h"'] + [f'#include "{h}"' for h in _used_includes(plan)]
    body += ["", _signature(plan, fn) + "{"]
    if plan.set_pose:
        body.append(_set_pose(plan))
    if plan.style == "lines":
        body += _lines_body(plan)
    else:
        steps = [s for _, s in plan.flat()]
        block = _sequence_block(steps, IND)
        body.append(IND + "return " + block[0])
        body += block[1:-1] + [block[-1] + ";"]
    body += ["}", ""]
    src = source_name(plan)
    return _stamp(header, src), _stamp("\n".join(body), src)


def export_paths(plan):
    fn = identifier(plan.name)
    return cfg.EXPORT_INC_DIR / f"{fn}.h", cfg.EXPORT_SRC_DIR / f"{fn}.cpp"


def hand_edited(path):
    """True if the file exists and isn't exactly what the tool last wrote (edited by hand, or not generated)."""
    if not path.exists():
        return False
    text = path.read_text()
    first, _, rest = text.partition("\n")
    if TAG not in first:
        return True
    return first.rsplit(TAG, 1)[1].strip() != hashlib.sha1(rest.encode()).hexdigest()[:12]


def write(plan):
    header, cpp = generate(plan)
    h_path, cpp_path = export_paths(plan)
    for path, text in ((h_path, header), (cpp_path, cpp)):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, newline="\n")
    return h_path, cpp_path
